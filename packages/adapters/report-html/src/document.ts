/**
 * Document skeleton (Template Method — e4-plan.md #87): composes head → skip link →
 * header → TOC → grouped workflow sections → footer in fixed order. The ONLY consumer
 * of trustedRaw is the static stylesheet/skeleton; every dynamic value flows through
 * the `html` boundary.
 *
 * Self-contained (NFR2/T5): single <style> block, no external refs, restrictive
 * <meta> CSP (defense-in-depth; load-bearing once E5 serves the artifact over http).
 */
import type { SafeHtml } from "./html.js";
import { html, trustedRaw } from "./html.js";
import type { FeatureGroupView, ReportView } from "./viewmodel.js";
import { REPORT_STYLESHEET } from "./assets/styles.js";
import { renderHeader, formatIsoTimestamp } from "./sections/header.js";
import { renderToc } from "./sections/toc.js";
import { renderWorkflow } from "./sections/workflow.js";

/**
 * Threat-model M87.5 ruling verbatim. Note: under this policy a reference-mode
 * (embedScreenshots:false) artifact served over http(s) will not load file-path
 * images — accepted; embed mode is the default self-contained path.
 */
export const META_CSP = "default-src 'none'; img-src data:; style-src 'unsafe-inline'";

export interface DocumentContext {
  /** Escaped and used for <title>; defaults to a FlowScout title with the appId. */
  readonly title: string;
  /** ISO-8601 render timestamp (from the injected clock — the only varying output). */
  readonly renderedAt: string;
  /** Resolved safe screenshot src per raw screenshotUri. */
  readonly screenshotSrcByUri: ReadonlyMap<string, string | null>;
}

function renderGroupSection(
  group: FeatureGroupView,
  screenshotSrcByUri: ReadonlyMap<string, string | null>,
): SafeHtml {
  const articles = group.workflows.map((workflow) => renderWorkflow(workflow, screenshotSrcByUri));
  return html`<section class="fs-group" data-group="${group.name}">
    <h2>${group.name}</h2>
    ${articles}
  </section>`;
}

function renderFooter(view: ReportView, renderedAt: string): SafeHtml {
  return html`<footer class="fs-footer">
    <p>
      Generated by FlowScout · run ${view.runId} ·
      <time datetime="${renderedAt}">${formatIsoTimestamp(renderedAt)}</time>
    </p>
  </footer>`;
}

export function renderDocument(view: ReportView, context: DocumentContext): SafeHtml {
  const sections = view.groups.map((group) =>
    renderGroupSection(group, context.screenshotSrcByUri),
  );
  return html`<!doctype html>
    <html lang="en">
      <head>
        <meta charset="utf-8" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <meta http-equiv="Content-Security-Policy" content="${META_CSP}" />
        <title>${context.title}</title>
        ${trustedRaw(`<style>${REPORT_STYLESHEET}</style>`)}
      </head>
      <body>
        <a class="fs-skip-link" href="#main-content">Skip to workflows</a>
        ${renderHeader(view.header)} ${renderToc(view.groups)}
        <main id="main-content">${sections}</main>
        ${renderFooter(view, context.renderedAt)}
      </body>
    </html>`;
}
